ranks = ['ace','two','three','four','five','six','seven','eight','nine','ten','page','knight','queen','king']
rank_names = ['一','二','三','四','五','六','七','八','九','十','侍者','騎士','皇后','國王']
existing = {c['id'] for c in deck['cards']}
by_id = {c['id']: c for c in manifest['cards']}
for suit, (name, domain, readings) in suits.items():
    for i, rank in enumerate(ranks):
        key = f'{rank}_of_{suit}'
        if key in existing:
            continue
        upright, reversed_ = readings[i]
        deck['cards'].append(dict(id=key, number=i+1, numeral=by_id[key]['numeral'], name=name+rank_names[i],
            english=by_id[key]['english'].title(),
            upright=dict(keywords=themes[i]+'、'+domain, meaning=upright,
                advice='把這份提醒放回你現在面對的事情，選一個自己做得到的小步驟。'),
            reversed=dict(keywords='重新整理、'+domain, meaning=reversed_,
                advice='先留意最讓你費力的地方，調整步調，也允許自己尋求支持。')))
deck['version'] = 'pastel-full-deck-1'
assert len(deck['cards']) == 78
assert {c['id'] for c in deck['cards']} == set(by_id)
path.write_text(json.dumps(deck, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
print('Bound 78 matching card IDs with upright and reversed RPG readings; original majors retained.')
